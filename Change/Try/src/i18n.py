"""多语言界面（Polyglot UI）—— 把界面上的中文换成各国语言，并按语言套用对应字体。

设计要点
--------
1. **中文原文即 key**：界面里的每段文字都用创建时的中文原文做键查表替换，
   这样不需要给上千处调用点编号，也不会因为改动文案而错位。
2. **切换只动显示、不动逻辑**：位置/播放方式/画质这些下拉框的规范值存在
   `itemData`（中文 key）里，业务代码一律通过 `gui._combo_key()` 取值，
   因此界面翻译成任何语言都不会影响功能（详见 gui.py 的 `_bind_combo_keys`）。
3. **回退链**：某语言缺词条时按 `FALLBACK` 逐级回退（如 ja → en → 中文原文），
   保证永远不会出现空字符串；`missing()` 可以列出还没翻译的条目。
4. **字体**：`UI_FONTS` 按语言给出候选字体族，取系统里第一个装了的
   （例如日语 → Yu Gothic UI、韩语 → Malgun Gothic），见 `resolve_ui_font`。

词表按语言分块追加在文件末尾，便于维护。
"""
from __future__ import annotations

LANGS = [
    ("zh-CN", "简体中文"),
    ("zh-TW", "繁體中文"),
    ("en", "English"),
    ("ja", "日本語"),
    ("ko", "한국어"),
    ("ru", "Русский"),
    ("de", "Deutsch"),
    ("fr", "Français"),
]
DEFAULT_LANG = "zh-CN"

# 各语言推荐的界面字体（按优先级；取系统里第一个存在的，都没有就用系统默认）
UI_FONTS = {
    "zh-CN": ["Microsoft YaHei UI", "Microsoft YaHei", "SimHei"],
    "zh-TW": ["Microsoft JhengHei UI", "Microsoft JhengHei", "MingLiU"],
    "en": ["Segoe UI", "Microsoft YaHei UI", "Arial"],
    "ja": ["Yu Gothic UI", "Meiryo UI", "MS UI Gothic", "Yu Gothic"],
    "ko": ["Malgun Gothic", "Gulim", "Batang"],
    "ru": ["Segoe UI", "Tahoma", "Arial"],
    "de": ["Segoe UI", "Tahoma", "Arial"],
    "fr": ["Segoe UI", "Tahoma", "Arial"],
}

# 缺词条时的回退顺序（都在前面找不到就返回中文原文）
FALLBACK = {
    "zh-TW": ["zh-CN"],
    "en": ["zh-CN"],
    "ja": ["en", "zh-CN"],
    "ko": ["en", "zh-CN"],
    "ru": ["en", "zh-CN"],
    "de": ["en", "zh-CN"],
    "fr": ["en", "zh-CN"],
}

T: dict[str, dict[str, str]] = {}

_cur = DEFAULT_LANG


def set_lang(code: str) -> str:
    """切换当前语言；返回真正生效的语言码（未知语言码退回默认）。"""
    global _cur
    codes = [c for c, _n in LANGS]
    _cur = code if code in codes else DEFAULT_LANG
    return _cur


def lang() -> str:
    return _cur


def lang_name(code: str | None = None) -> str:
    code = code or _cur
    for c, n in LANGS:
        if c == code:
            return n
    return code


def tr(text: str) -> str:
    """把界面中文换成当前语言；没词条时按回退链找，最后原样返回。"""
    if not text or _cur == DEFAULT_LANG:
        return text
    for code in [_cur] + FALLBACK.get(_cur, []):
        d = T.get(code)
        if d and text in d:
            return d[text]
    return text


def trf(template: str, **kw) -> str:
    """带占位符的整句翻译：template 用 `{name}` 占位，译文里同样带占位符。

    注意：占位符必须用命名形式（`{kinds_desc}` 而不是 `{}`），
    否则各语言语序不同时无法调整位置。
    """
    out = tr(template)
    try:
        return out.format(**kw)
    except Exception:          # 译文占位符写错也不能崩，退回原文格式
        return template.format(**kw)


def has(text: str) -> bool:
    return text in T.get(_cur, {})


def missing(keys) -> list[str]:
    """列出当前语言还没翻译的 key（用于自检/补词条）。"""
    d = T.get(_cur, {})
    return [k for k in keys if k not in d]


def coverage() -> dict[str, tuple[int, int]]:
    """各语言覆盖度：(已译条数, 全量 key 数)——全量取所有语言 key 的并集。"""
    all_keys = set()
    for d in T.values():
        all_keys |= set(d)
    n = len(all_keys)
    return {code: (len(T.get(code, {})), n) for code, _name in LANGS}


def resolve_ui_font(code: str) -> str:
    """该语言在系统里可用的界面字体名；一个都没有时返回空串（用系统默认）。"""
    try:
        from PySide6.QtGui import QFontDatabase
        fams = set(QFontDatabase.families())
    except Exception:
        return ""
    for name in UI_FONTS.get(code, []):
        if name in fams:
            return name
    return ""


